export type Key = keyof (typeof dict)["es"];

interface Ctx {
  lang: Lang;
  t: (key: Key, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const { settings } = useStore();
  const lang: Lang = settings.language === "auto" ? (navigator.language.toLowerCase().startsWith("es") ? "es" : "en") : settings.language;

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = useCallback<Ctx["t"]>(
    (key, vars) => {
      let s: string = dict[lang][key] ?? dict.es[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, t }), [lang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n outside I18nProvider");
  return c;
}
